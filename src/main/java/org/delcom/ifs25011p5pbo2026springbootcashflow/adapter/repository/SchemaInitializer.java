package org.delcom.ifs25011p5pbo2026springbootcashflow.adapter.repository;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** CREATE TABLE IF NOT EXISTS untuk users dan transactions. */
public final class SchemaInitializer {
    private SchemaInitializer() {
    }

    static final String USERS = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(100) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                full_name VARCHAR(200) NOT NULL,
                role VARCHAR(20) NOT NULL,
                photo_path VARCHAR(500)
            )""";

    static final String TRANSACTIONS = """
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                description TEXT NOT NULL,
                amount BIGINT NOT NULL,
                type VARCHAR(20) NOT NULL,
                proof_path VARCHAR(500),
                created_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
            )""";

    static final String INDEX = "CREATE INDEX IF NOT EXISTS idx_transactions_user ON transactions(user_id)";

    public static void initialize(DataSource dataSource) {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(USERS);
            statement.execute(TRANSACTIONS);
            statement.execute(INDEX);
        } catch (SQLException e) {
            throw new IllegalStateException("Gagal membuat skema database", e);
        }
    }
}
